-- Reproducible storage bucket configuration for product photos.
-- Public reads are intentional for marketplace product imagery.
-- Upload/update/delete access remains restricted by the owner-scoped
-- storage.objects policies in the product image policy migrations.

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'product-images',
  'product-images',
  true,
  8388608,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set
  name = excluded.name,
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
